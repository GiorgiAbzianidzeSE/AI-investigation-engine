"""Render the synthetic incident corpus (scripts/incident_texts.py) into data/incidents/.

    uv run python -m scripts.make_incidents

Output is deterministic, so the committed files can be regenerated byte for byte (PDF/DOCX metadata dates
are pinned).
"""
import html
from datetime import datetime, timezone
from pathlib import Path

from scripts.incident_texts import ARCHITECTURE, DOCUMENTS, FRAUD_RUNBOOK

OUT = Path("data/incidents")
FIXED_DATE = datetime(2026, 3, 31, tzinfo=timezone.utc)


def _kv_lines(fields):
    return [f"{k}: {v}".rstrip() for k, v in fields]


def to_markdown(doc) -> str:
    out = []
    for kind, val in doc["blocks"]:
        if kind == "h1":
            out.append(f"# {val}")
        elif kind == "h2":
            out.append(f"## {val}")
        elif kind == "p":
            out.append(val)
        elif kind == "ul":
            out.append("\n".join(f"- {i}" for i in val))
        elif kind == "kv":
            out.append("\n".join(f"{line}  " for line in _kv_lines(val)))
        elif kind == "table":
            head, *rows = val
            lines = [" | ".join(head), " | ".join("---" for _ in head)] + [" | ".join(r) for r in rows]
            out.append("\n".join(f"| {line} |" for line in lines))
    return "\n\n".join(out) + "\n"


def to_html(doc) -> str:
    e = html.escape
    body = []
    for kind, val in doc["blocks"]:
        if kind in ("h1", "h2"):
            body.append(f"<{kind}>{e(val)}</{kind}>")
        elif kind == "p":
            body.append(f"<p>{e(val)}</p>")
        elif kind == "ul":
            body.append("<ul>" + "".join(f"<li>{e(i)}</li>" for i in val) + "</ul>")
        elif kind == "kv":
            body.append("".join(f"<p>{e(line)}</p>" for line in _kv_lines(val)))
        elif kind == "table":
            head, *rows = val
            body.append("<table><tr>" + "".join(f"<th>{e(h)}</th>" for h in head) + "</tr>"
                        + "".join("<tr>" + "".join(f"<td>{e(c)}</td>" for c in r) + "</tr>" for r in rows)
                        + "</table>")
    return ("<!DOCTYPE html>\n<html><head><meta charset=\"utf-8\"><title>" + e(doc["title"]) + "</title>"
            "<style>body{font-family:sans-serif;max-width:50em}td,th{border:1px solid #ccc;padding:4px}</style>"
            "</head><body>\n<nav>Northwind Payments intranet</nav>\n" + "\n".join(body)
            + "\n<footer>Internal - Northwind Payments</footer>\n</body></html>\n")


def to_docx(doc) -> bytes:
    import io

    import docx

    d = docx.Document()
    d.core_properties.title = doc["title"]
    d.core_properties.author = "Northwind Payments"
    d.core_properties.created = d.core_properties.modified = FIXED_DATE.replace(tzinfo=None)
    for kind, val in doc["blocks"]:
        if kind in ("h1", "h2"):
            d.add_heading(val, level=1 if kind == "h1" else 2)
        elif kind == "p":
            d.add_paragraph(val)
        elif kind == "ul":
            for item in val:
                d.add_paragraph(item, style="List Bullet")
        elif kind == "kv":
            for line in _kv_lines(val):
                d.add_paragraph(line)
        elif kind == "table":
            head, *rows = val
            t = d.add_table(rows=0, cols=len(head))
            for r in [head, *rows]:
                for cell, text in zip(t.add_row().cells, r):
                    cell.text = text
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


def to_pdf(doc) -> bytes:
    from fpdf import FPDF

    pdf = FPDF()
    pdf.set_title(doc["title"])
    pdf.set_author("Northwind Payments")
    pdf.set_creation_date(FIXED_DATE)
    pdf.set_auto_page_break(True, margin=15)
    pdf.add_page()

    def para(text, style="", size=11, h=6):
        pdf.set_font("Helvetica", style, size)
        pdf.multi_cell(0, h, text, new_x="LMARGIN", new_y="NEXT")

    for kind, val in doc["blocks"]:
        if kind == "h1":
            para(val, "B", 16, 9)
            pdf.ln(3)
        elif kind == "h2":
            pdf.ln(2)
            para(val, "B", 13, 8)
        elif kind == "p":
            para(val)
            pdf.ln(3)
        elif kind == "ul":
            for item in val:
                para(f"- {item}")
            pdf.ln(3)
        elif kind == "kv":
            for line in _kv_lines(val):
                para(line)
            pdf.ln(3)
        elif kind == "table":
            for r in val:
                para(" | ".join(r))
            pdf.ln(3)
    return bytes(pdf.output())


RENDER = {".md": to_markdown, ".html": to_html, ".docx": to_docx, ".pdf": to_pdf}


def render(doc):
    data = RENDER[Path(doc["filename"]).suffix](doc)
    return data.encode("ascii") if isinstance(data, str) else data


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for doc in DOCUMENTS:
        (OUT / doc["filename"]).write_bytes(render(doc))
        print("wrote", OUT / doc["filename"])

    demo = OUT / "dedup-demo"
    (demo / "edited").mkdir(parents=True, exist_ok=True)
    # 1) byte-identical copy -> duplicate
    (demo / "fraud-scorer-runbook-copy.md").write_bytes(render(FRAUD_RUNBOOK))
    # 2) one extra line -> near duplicate of payments-architecture.md
    v2 = {**ARCHITECTURE, "blocks": ARCHITECTURE["blocks"] + [("p", "Last reviewed: 2026-03-28")]}
    (demo / "payments-architecture-v2.md").write_bytes(render(v2))
    # 3) same filename, new section -> upload with replace=true gives version 2
    v2_edited = {**v2, "blocks": v2["blocks"] + [
        ("h2", "Changelog"),
        ("ul", ["2026-03-28: reviewed after the March incidents; no structural changes.",
                "2026-03-30: added a note that nightly job schedules must not overlap."]),
    ]}
    (demo / "edited" / "payments-architecture-v2.md").write_bytes(render(v2_edited))
    print("wrote dedup demo files in", demo)


if __name__ == "__main__":
    main()
